def main() -> None:
    configure_logging("INFO")
    init_db()
    started = time.monotonic()
    total_chunks = 0
    for doc in DOCS:
        result = upsert_document(
            collection=doc["collection"],
            content=doc["content"],
            title=doc["title"],
            doc_id=doc["doc_id"],
            source=doc.get("source", "manual"),
        )
        total_chunks += result["chunks"]
        print(f"[{result['action']:7s}] {result['doc_id']:20s} chunks={result['chunks']}")
    elapsed = int((time.monotonic() - started) * 1000)
    print(f"\n共 {len(DOCS)} 条文档，{total_chunks} 个切片，耗时 {elapsed} ms")


if __name__ == "__main__":
    main()
